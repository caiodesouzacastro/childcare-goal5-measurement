main = open(os.path.join(P, "paper_v4.tex"), encoding="utf-8").read()
def strip(s): return re.sub(r"(?m)(?<!\\)%.*$", "", s)
def expand(s, depth=0):
    s = strip(s)
    if depth > 5: return s
    def rep(m):
        f = m.group(1); f = f if f.endswith(".tex") else f + ".tex"
        if "tables_V3" in f: return ""
        fp = os.path.join(P, f)
        return expand(open(fp, encoding="utf-8").read(), depth + 1) if os.path.exists(fp) else ""
    return re.sub(r"\\input\{([^}]+)\}", rep, s)
body = expand(main[:main.index("\\appendix")])
idx = list(csv.DictReader(open(os.path.join(P, r"assets\tables\v3w\float_index_v3.csv"), encoding="utf-8")))
for it in idx:
    it["labels"] = it["labels"].split(";")
    it["text"] = strip(open(os.path.join(P, it["file"] + ".tex"), encoding="utf-8").read())
    for l in it["labels"]: assert "\\label{" + l + "}" in it["text"], (it["file"], l)
def first(it, text):
    pos = [text.find("\\ref{" + l + "}") for l in it["labels"]]; pos = [p for p in pos if p >= 0]
    return min(pos) if pos else None
def order(cands, texts):
    placed, rem = [], cands[:]
    for t in texts:
        for it in sorted([i for i in rem if first(i, t) is not None], key=lambda i: first(i, t)):
            placed.append(it)
        rem = [i for i in rem if i not in placed]
    changed = True
    while rem and changed:
        changed = False; txt = "".join(i["text"] for i in placed)
        cand = [i for i in rem if first(i, txt) is not None]
        if cand:
            c = min(cand, key=lambda i: first(i, txt)); placed.append(c); rem.remove(c); changed = True
    return placed, rem
B = [i for i in idx if i["place"] == "body"]; A = [i for i in idx if i["place"] == "appx"]
bp, br = order(B, [body])
ap, ar = order(A, [body, "".join(i["text"] for i in bp)])
hdr = "% {} -- generated by 02_audit/build12_order.py (FUSAO, 26/10/2026): floats in order of first citation. Do not edit by hand."
def num(lst, pre):
    nt = nf = 0; out = []
    for i in lst:
        if i["labels"][0].startswith("fig:"): nf += 1; out.append(f"{pre}Fig.{nf}={i['labels'][0]}")
        else: nt += 1; out.append(f"{pre}{nt}={i['labels'][0]}")
    return out
porarq = {i["file"]: i for i in idx}
for nome, lst, pre in (("tables_V3.tex", bp + br, ""), ("tables_V3_appendix.tex", ap + ar, "A")):
    fp = os.path.join(P, nome)
    novo = "\n".join([hdr.format(nome)] + ["\\input{" + i["file"] + "}" for i in lst]) + "\n"
    velho = open(fp, encoding="utf-8").read() if os.path.exists(fp) else ""
    antes = [porarq[f] for f in re.findall(r"\\input\{([^}]+)\}", velho) if f in porarq]
    n_antes = dict(x.split("=", 1)[::-1] for x in num(antes, pre)); n_novo = dict(x.split("=", 1)[::-1] for x in num(lst, pre))
    mud = [f"{l}: {n_antes.get(l, '-')} -> {n_novo.get(l, '-')}" for l in sorted(set(n_antes) | set(n_novo)) if n_antes.get(l) != n_novo.get(l)]
    print(f"MUDANCAS {nome}: {len(mud)}" + ("" if not mud else " | " + "; ".join(mud)))
    if novo.replace("\r\n", "\n") == velho.replace("\r\n", "\n"):
        print(f"  {nome}: inalterado (nao regravado)")
    elif SECO:
        print(f"  {nome}: diferente; --seco, nao gravado")
    else:
        open(fp, "w", encoding="utf-8").write(novo); print(f"  {nome}: regravado")
